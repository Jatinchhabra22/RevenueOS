from pathlib import Path

from langchain_core.runnables import RunnableConfig

from app.agents.audit import append_audit, require_context
from app.agents.state import AgentState
from app.services.prediction.inference import predict_churn, predict_recovery


def get_predictions_node(state: AgentState, config: RunnableConfig) -> AgentState:
    if state.get("recovery_prediction") and state.get("churn_prediction"):
        trail = append_audit(state, "get_predictions", "injected", "Predictions already present on state.")
        return {"audit_trail": trail}

    context = require_context(state)
    artifacts = ((config or {}).get("configurable") or {}).get("artifacts_dir")
    artifacts_dir = Path(artifacts) if artifacts else None
    recovery = predict_recovery(context, artifacts_dir)
    churn = predict_churn(context, artifacts_dir)
    trail = append_audit(
        state,
        "get_predictions",
        "scored",
        "Recovery and churn probabilities generated by ML services.",
        {
            "recovery_probability": recovery.probability,
            "churn_probability": churn.probability,
        },
    )
    return {
        "recovery_prediction": recovery.model_dump(mode="json"),
        "churn_prediction": churn.model_dump(mode="json"),
        "audit_trail": trail,
    }
